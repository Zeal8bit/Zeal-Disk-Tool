"""Generate include/ui_icons.h from the SVG files in packages/icons/lucide.

The SVGs keep Lucide's `currentColor` stroke so the renderer can tint each
icon at load time. Re-run this script after adding or updating an icon.

It also embeds packages/icons/zeal-disk-tool_256.png as include/app_icon_png.h
and the outlined wordmark in packages/icons/zeal-disk-tool-wordmark.svg as
include/app_wordmark.h, so the About window needs no image files at runtime.
"""
from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "packages" / "icons" / "lucide"
TARGET = ROOT / "include" / "ui_icons.h"
APP_ICON = ROOT / "packages" / "icons" / "zeal-disk-tool_256.png"
APP_ICON_TARGET = ROOT / "include" / "app_icon_png.h"
WORDMARK = ROOT / "packages" / "icons" / "zeal-disk-tool-wordmark.svg"
WORDMARK_TARGET = ROOT / "include" / "app_wordmark.h"

HEADER = """/**
 * SPDX-FileCopyrightText: 2026 Zeal 8-bit Computer <contact@zeal8bit.com>
 *
 * SPDX-License-Identifier: Apache-2.0
 */
#pragma once

#include <cstddef>

/* Generated by scripts/generate-icons.py from the SVG files in packages/icons/lucide.
 * Icons: Lucide (https://lucide.dev), ISC License; see
 * packages/icons/lucide/LICENSE. The sources use `currentColor`, which the
 * renderer replaces with the requested colour before rasterising. */
namespace modern {
namespace icons {

struct IconSource {
    const char *name;
    const char *svg;
    size_t size;
};

static const IconSource kSources[] = {
"""

FOOTER = """};

static const size_t kSourceCount = sizeof(kSources) / sizeof(kSources[0]);

}  // namespace icons
}  // namespace modern
"""


APP_ICON_HEADER = """/**
 * SPDX-FileCopyrightText: 2026 Zeal 8-bit Computer <contact@zeal8bit.com>
 *
 * SPDX-License-Identifier: Apache-2.0
 */
#pragma once

/* Generated by scripts/generate-icons.py from
 * packages/icons/zeal-disk-tool_256.png. PNG bytes decoded by Fl_PNG_Image for
 * the About window; the window icon uses the smaller app_icon.h array. */
static const unsigned char s_about_icon_png[] = {
"""

APP_ICON_FOOTER = """};
"""


WORDMARK_HEADER = """/**
 * SPDX-FileCopyrightText: 2026 Zeal 8-bit Computer <contact@zeal8bit.com>
 *
 * SPDX-License-Identifier: Apache-2.0
 */
#pragma once

/* Generated by scripts/generate-icons.py from
 * packages/icons/zeal-disk-tool-wordmark.svg. The wordmark outlines the
 * Righteous typeface (SIL OFL 1.1, see packages/icons/righteous-OFL.txt). */
#define APP_WORDMARK_WIDTH %d
#define APP_WORDMARK_HEIGHT %d
#define APP_WORDMARK_SVG R"SVG(%s)SVG"
"""


def write_wordmark() -> None:
    svg = WORDMARK.read_text(encoding="utf-8").strip()
    match = re.search(r'width="(\d+)" height="(\d+)"', svg)
    if match is None:
        raise SystemExit(f"{WORDMARK}: missing width/height")
    width, height = int(match.group(1)), int(match.group(2))
    if ')SVG"' in svg:
        raise SystemExit(f"{WORDMARK}: contains the raw string delimiter")
    WORDMARK_TARGET.write_text(WORDMARK_HEADER % (width, height, svg), encoding="utf-8")
    print(f"wrote {WORDMARK_TARGET.relative_to(ROOT)} ({width}x{height})")


def write_about_icon() -> None:
    data = APP_ICON.read_bytes()
    parts = [APP_ICON_HEADER]
    for offset in range(0, len(data), 12):
        chunk = data[offset : offset + 12]
        parts.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",\n")
    parts.append(APP_ICON_FOOTER)
    APP_ICON_TARGET.write_text("".join(parts), encoding="utf-8")
    print(f"wrote {APP_ICON_TARGET.relative_to(ROOT)} with {len(data)} bytes")


def main() -> int:
    icons = sorted(SOURCE.glob("*.svg"))
    if not icons:
        print(f"no icons found in {SOURCE}", file=sys.stderr)
        return 1
    parts = [HEADER]
    for path in icons:
        data = path.read_text(encoding="utf-8").strip()
        if ')ICON"' in data:
            print(f"{path.name}: contains the raw string delimiter", file=sys.stderr)
            return 1
        parts.append(f'    {{"{path.stem}", R"ICON({data})ICON", {len(data.encode("utf-8"))}}},\n')
    parts.append(FOOTER)
    TARGET.write_text("".join(parts), encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} with {len(icons)} icons")
    write_about_icon()
    write_wordmark()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
